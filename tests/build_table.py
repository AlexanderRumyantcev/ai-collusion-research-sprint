#!/usr/bin/env python3
"""Build data/cases.md and data/cases.csv from the generated test output.

Inputs (produced by `npm test`, do not edit by hand):
  results/items.csv   one row per evidence type (T01-T12, X1-X5)
  results/cases.csv   one row per case configuration (C0-C11)

Outputs:
  results/table.md    the final table in the report's form
  results/table.csv   the same table, machine-readable

Run: npm run table   (or: python3 tests/build_table.py)
"""

import csv
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"
ITEMS = RESULTS / "items.csv"
CASES = RESULTS / "cases.csv"
OUT_MD = RESULTS / "table.md"
OUT_CSV = RESULTS / "table.csv"


def read(path):
    with path.open(encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def source_cell(row):
    urls = [u for u in row["source_urls"].split() if u]
    if not urls:
        return "no public source (own run, not archived)"
    return "<br>".join(urls)


def verdict_cell(row):
    weight = row["signed_weight"]
    element = row["graph_element"] or "—"
    if row["enters_demo_verdict"] == "yes":
        return f"{element} {weight}"
    if row["graph_element"]:
        return f"{element} {weight} (does not enter a verdict)"
    return f"none: weight {weight}, no element in the demo"


def main():
    items = read(ITEMS)
    cases = read(CASES)

    lines = []
    add = lines.append
    add("# Cases and the graph's answer")
    add("")
    add("Generated by `tests/build_table.py` from `results/items.csv` and")
    add("`results/cases.csv`, which `npm test` writes. Do not edit by hand.")
    add("")
    add("The graph is a rule engine: its answer follows from the labels, so the")
    add("tables show how the method behaves on this labelling, not whether the")
    add("labelling is correct. Labels were assigned by one rater (the author).")
    add("")
    add("## 1. Evidence types from published work")
    add("")
    add("Every row of the dataset, in the order the test output produces them,")
    add("with no rows dropped. `scored` rows carry the element they bear on in")
    add("the report and the weight the graph gives them; `excluded` rows were")
    add("read and deliberately left unscored, and the last column says why.")
    add("`weight` is the ordinal weight of the item (4 direct and reliable,")
    add("3 direct and doubtful, 2 circumstantial and reliable, 1 circumstantial")
    add("and doubtful, 0 unreliable); a negative weight is exculpatory.")
    add("")
    add("| id | status | case (short) | source | element in the demo | weight | usable in a verdict | note |")
    add("|---|---|---|---|---|---|---|---|")
    for r in items:
        scored = r["status"] == "scored"
        add(
            "| {id} | {st} | {title} | {src} | {el} | {w} | {u} | {note} |".format(
                id=r["id"],
                st=r["status"],
                title=r["title"].replace("|", "/"),
                src=source_cell(r),
                el=(r["graph_element"] or "—") if scored else "—",
                w=r["signed_weight"] if scored else "—",
                u=("yes" if r["enters_demo_verdict"] == "yes" else "no") if scored else "—",
                note="" if scored else r["rationale"].replace("|", "/"),
            )
        )
    add("")
    add("Among the scored rows, `no` means the item gets a weight but cannot")
    add("change a verdict, because the demo has no node for coordination (E1)")
    add("or for counterfactual harm (E4), or because the item bears on the")
    add("claim as a whole rather than on one element.")
    add("")
    add("## 2. Case configurations and the standard reached")
    add("")
    add("A configuration is a set of evidence available in one case. The")
    add("standard reached is the highest rung of the ladder the evidence meets:")
    add("reasonable suspicion, probable cause, substantial evidence,")
    add("preponderance of the evidence, clear and convincing evidence, beyond a")
    add("reasonable doubt. `f` items are the demo's preset items about a")
    add("hypothetical episode, not published data.")
    add("")
    add("| case | what the case contains | evidence | element states | standard reached |")
    add("|---|---|---|---|---|")
    for r in cases:
        add(
            "| {id} | {name} | {items} | {states} | {std} |".format(
                id=r["case"],
                name=r["name"].replace("|", "/"),
                items=r["items"].replace(" ", ", ") or "—",
                states=r["element_states"],
                std=r["standard_reached"],
            )
        )
    add("")
    add("The verdict is limited by the weakest element; `*` in the element")
    add("states marks independent corroboration.")
    add("")
    add("## 3. Machine-readable form")
    add("")
    add("`results/table.csv` holds table 1; `results/cases.csv` holds table 2")
    add("with the element states unflattened. Both are regenerated, not edited.")
    add("")

    OUT_MD.write_text("\n".join(lines), encoding="utf-8")

    with OUT_CSV.open("w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(
            [
                "id",
                "status",
                "case_short",
                "source_urls",
                "element_in_demo",
                "weight",
                "usable_in_verdict",
                "direction",
                "directness",
                "reliability",
            ]
        )
        for r in items:
            w.writerow(
                [
                    r["id"],
                    r["status"],
                    r["title"],
                    r["source_urls"],
                    r["graph_element"],
                    r["signed_weight"],
                    r["enters_demo_verdict"],
                    r["direction"],
                    r["directness"],
                    r["reliability"],
                ]
            )

    scored = sum(1 for r in items if r["status"] == "scored")
    print(f"wrote {OUT_MD.relative_to(ROOT)} ({scored} scored, {len(items) - scored} excluded)")
    print(f"wrote {OUT_CSV.relative_to(ROOT)} ({len(items)} rows)")


if __name__ == "__main__":
    main()
